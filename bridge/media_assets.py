MAX_IMAGE = 8 * 1024 * 1024
MAX_VOICE = 20 * 1024 * 1024
DEFAULT_CACHE = 256 * 1024 * 1024
MEDIA_TYPES = {3: "image", 34: "voice", 43: "video", 47: "sticker", 11000: "sticker"}
STICKER_FRAMES = 4
MAX_ANIMATION_FRAMES = 1000
MAX_FRAME_BYTES = 2 * 1024 * 1024
_STICKER_ID = re.compile(r"[a-f0-9]{32}")
_STICKER_PACK = re.compile(r"[A-Za-z0-9_.\-]{1,128}")
# Store captions carry several languages; the Chinese one is preferred, then WeChat's default.
_CAPTION_LANGUAGES = ("zh_cn", "default", "zh_tw")


class MediaUnavailable(RuntimeError):
    """A bounded public reason, never a filename, source XML or decoder output."""


def media_kind(local_type):
    return MEDIA_TYPES.get(local_type & 0xFFFFFFFF if isinstance(local_type, int) else local_type)


def media_metadata(local_type, content):
    kind = media_kind(local_type)
    if not kind:
        return None
    result = {"kind": kind}
    if not isinstance(content, str) or len(content) > 128000 or "<!DOCTYPE" in content.upper():
        return result
    start = content.find("<")
    if start < 0:
        return result
    try:
        root = ElementTree.fromstring(content[start:].strip())
    except ElementTree.ParseError:
        return result
    tag = {"image": "img", "voice": "voicemsg", "video": "videomsg", "sticker": "emoji"}[kind]
    node = root if root.tag == tag else root.find(".//" + tag)
    if node is not None:
        for attr, field, scale, maximum in (("width", "width", 1, 50000), ("height", "height", 1, 50000),
                ("voicelength" if kind == "voice" else "playlength", "durationMs", 1 if kind == "voice" else 1000, 36000000)):
            raw = node.get(attr, "")
            if raw.isdigit() and 0 < int(raw) * scale <= maximum:
                result[field] = int(raw) * scale
    if kind == "voice":
        # WeChat's own completed transcription, never generated by this application.
        trans = root.find(".//voicetrans")
        if trans is not None and trans.get("istransend", "1") == "1":
            value = trans.get("transtext") or trans.findtext("transtext") or trans.text or ""
            if value.strip() and len(value) <= 20000:
                result.update(transcript=value.strip(), transcriptSource="wechat")
    return result


@dataclass(frozen=True)
class MediaAsset:
    mime: str
    data: bytes | None = None
    path: Path | None = None

    def read(self):
        return self.data if self.data is not None else self.path.read_bytes()


def image_mime(data):
    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if data.startswith((b"GIF87a", b"GIF89a")):
        return "image/gif"
    if data.startswith(b"RIFF") and data[8:12] == b"WEBP":
        return "image/webp"
    raise MediaUnavailable("unsupported-format")


def _reparse(path):
    try:
        return path.is_symlink() or bool(getattr(path.lstat(), "st_file_attributes", 0) & 0x400)
    except FileNotFoundError:
        return False


def analysis_image(data):
    """A provider-safe still image; animated files contribute their first frame only."""
    try:
        from PIL import Image, ImageOps
        with Image.open(io.BytesIO(data)) as source:
            animated = bool(getattr(source, "is_animated", False))
            source.seek(0)
            rgba = ImageOps.exif_transpose(source).convert("RGBA")
            # JPEG has no alpha. Keep transparent stickers' dark outlines visible
            # on the same light backdrop commonly used in the chat display.
            image = Image.new("RGB", rgba.size, "white")
            image.paste(rgba, mask=rgba.getchannel("A"))
            for size in (1600, 1200, 800, 480):
                image.thumbnail((size, size))
                output = io.BytesIO()
                image.save(output, "JPEG", quality=85)
                if len(output.getvalue()) <= 2 * 1024 * 1024:
                    return output.getvalue(), animated
    except ImportError:
        raise MediaUnavailable("image-decoder-unavailable") from None
    except Exception:
        raise MediaUnavailable("image-decode-failed") from None
    raise MediaUnavailable("analysis-image-too-large")


def analysis_frames(data, max_frames=STICKER_FRAMES):
    """Up to ``max_frames`` provider-safe stills spread over an animation's playing time.

    Returns ``(frames, duration_ms)`` with ``frames`` as ``[(jpeg, time_ms)]``. A still image gives one
    frame and a duration of 0. A frame that looks like the one kept before it is skipped.
    """
    try:
        from PIL import Image, ImageChops, ImageStat
        with Image.open(io.BytesIO(data)) as source:
            count = getattr(source, "n_frames", 1) if getattr(source, "is_animated", False) else 1
            if count <= 1:
                return [(analysis_image(data)[0], 0)], 0
            starts, total = [], 0
            for index in range(min(count, MAX_ANIMATION_FRAMES)):
                source.seek(index)
                duration = source.info.get("duration")
                # Players show missing or very short GIF delays as 100 ms.
                duration = int(duration) if isinstance(duration, (int, float)) and duration > 10 else 100
                starts.append(total)
                total += duration
            picks = []
            for slot in range(max_frames):
                target = total * slot // max_frames
                index = max(position for position, start in enumerate(starts) if start <= target)
                if index not in picks:
                    picks.append(index)
            frames, previous = [], None
            for index in picks:
                source.seek(index)
                rgba = source.convert("RGBA")
                image = Image.new("RGB", rgba.size, "white")
                image.paste(rgba, mask=rgba.getchannel("A"))
                image.thumbnail((480, 480))
                probe = image.convert("L").resize((16, 16))
                if previous is not None and sum(ImageStat.Stat(ImageChops.difference(probe, previous)).mean) < 3:
                    continue
                previous = probe
                output = io.BytesIO()
                image.save(output, "JPEG", quality=85)
                frames.append((output.getvalue(), starts[index]))
            return frames, total
    except ImportError:
        raise MediaUnavailable("image-decoder-unavailable") from None
    except MediaUnavailable:
        raise
    except Exception:
        raise MediaUnavailable("image-decode-failed") from None


def _varint(data, index):
    result = shift = 0
    while True:
        if index >= len(data) or shift > 63:
            raise ValueError("truncated varint")
        byte = data[index]
        index += 1
        result |= (byte & 0x7F) << shift
        if not byte & 0x80:
            return result, index
        shift += 7


def _protobuf_fields(data):
    """``(field, bytes)`` of one protobuf message's length-delimited fields; varints are skipped."""
    fields, index = [], 0
    while index < len(data):
        key, index = _varint(data, index)
        if key & 7 == 2:
            length, index = _varint(data, index)
            if index + length > len(data):
                raise ValueError("truncated field")
            fields.append((key >> 3, data[index:index + length]))
            index += length
        elif key & 7 == 0:
            _value, index = _varint(data, index)
        else:
            raise ValueError("unsupported wire type")
    return fields


def _caption(captions):
    for language in _CAPTION_LANGUAGES:
        if captions.get(language):
            text = captions[language]
            break
    else:
        text = next(iter(captions.values()), "")
    text = " ".join(str(text).split())[:40]
    return text or None


def _desc_caption(value):
    """The caption a store sticker message carries in ``desc``: base64 of ``{1: {1: language, 2: text}}``."""
    if not isinstance(value, str) or not 0 < len(value) <= 4096:
        return None
    captions = {}
    try:
        for number, item in _protobuf_fields(base64.b64decode(value, validate=True)):
            if number != 1:
                continue
            parts = dict(_protobuf_fields(item))
            text = parts.get(2, b"").decode("utf-8").strip()
            if text:
                captions.setdefault(parts.get(1, b"").decode("utf-8").lower(), text)
    except (ValueError, binascii.Error, UnicodeDecodeError):
        return None
    return _caption(captions)


def sticker_identity(content):
    """The content MD5 of one sticker message, its store pack and the caption it carries, if any."""
    if not isinstance(content, str) or len(content) > 128000 or "<!DOCTYPE" in content.upper():
        return None
    start = content.find("<")
    if start < 0:
        return None
    try:
        root = ElementTree.fromstring(content[start:].strip())
    except ElementTree.ParseError:
        return None
    node = root if root.tag == "emoji" else root.find(".//emoji")
    identifier = node.get("md5", "").lower() if node is not None else ""
    if not _STICKER_ID.fullmatch(identifier):
        return None
    result = {"id": identifier}
    if _STICKER_PACK.fullmatch(node.get("productid", "")):
        result["pack"] = node.get("productid")
    caption = _desc_caption(node.get("desc"))
    if caption:
        result["caption"] = caption
    return result


def check_owned_path(path):
    """Reject every existing reparse component before reading, writing or deleting."""
    for part in (path, *path.parents):
        if _reparse(part):
            raise MediaUnavailable("media-storage-unavailable")


def clear_owned_media(path):
    check_owned_path(path)
    if not path.exists():
        return
    owned = path.resolve()
    files, directories, pending = [], [path], [path]
    while pending:
        for item in pending.pop().iterdir():
            if _reparse(item) or not item.resolve().is_relative_to(owned):
                raise MediaUnavailable("media-storage-unavailable")
            if item.is_dir():
                directories.append(item)
                pending.append(item)
            elif item.is_file():
                files.append(item)
            else:
                raise MediaUnavailable("media-storage-unavailable")
    # Paths are fully verified before any delete, and no recursive shell removal is used.
    for item in files:
        item.unlink()
    for item in sorted(directories, key=lambda entry: len(entry.parts), reverse=True):
        item.rmdir()


class LocalMedia:
    def __init__(self, db, downloader, storage_root=None):
        self.db, self.downloader = db, downloader
        self.root = Path(storage_root).absolute() if storage_root is not None else (
            Path(db.workdir).absolute() / "media" if getattr(db, "workdir", None) else None)
        self.lock = threading.RLock()
        self.condition = threading.Condition()
        self.active, self.closed = 0, False
        self._video_paths = {}
        self._sticker_locks = [threading.Lock() for _ in range(16)]
        self._sticker_failures = {}
        self.mode, self.cache_max = "archive", DEFAULT_CACHE
        if self.root is not None:
            check_owned_path(self.root)
            if _reparse(self.root) or self.root.resolve() != self.root:
                raise MediaUnavailable("media-storage-unavailable")
            self.root.mkdir(parents=True, exist_ok=True)
            try:
                config = self.root / "settings.json"
                if _reparse(config) or config.exists() and config.stat().st_size > 4096:
                    raise MediaUnavailable("media-storage-unavailable")
                value = json.loads(config.read_text(encoding="utf-8"))
                self._validate_settings(value)
                self.mode = value.get("mode", self.mode)
                self.cache_max = value.get("cacheMaxBytes", self.cache_max)
            except (OSError, ValueError, TypeError):
                pass

    @contextmanager
    def operation(self):
        with self.condition:
            if self.closed:
                raise MediaUnavailable("account-clearing")
            self.active += 1
        try:
            yield self
        finally:
            with self.condition:
                self.active -= 1
                self.condition.notify_all()

    def close(self):
        with self.condition:
            self.closed = True
            while self.active:
                self.condition.wait()

    @staticmethod
    def _validate_settings(value):
        if not isinstance(value, dict) or set(value) - {"mode", "cacheMaxBytes"}:
            raise ValueError("invalid media settings")
        if "mode" in value and value["mode"] not in ("reference", "archive"):
            raise ValueError("invalid media storage mode")
        size = value.get("cacheMaxBytes", DEFAULT_CACHE)
        if type(size) is not int or not 16 * 1024 * 1024 <= size <= 2 * 1024 * 1024 * 1024:
            raise ValueError("invalid media cache size")

    def _folder(self, name):
        if self.root is None:
            raise MediaUnavailable("media-storage-unavailable")
        path = self.root / name
        path.mkdir(exist_ok=True)
        if _reparse(path) or not path.resolve().is_relative_to(self.root):
            raise MediaUnavailable("media-storage-unavailable")
        return path

    def _files(self, name):
        if self.root is None or not (self.root / name).exists():
            return []
        return [path for path in self._folder(name).iterdir()
                if path.is_file() and not _reparse(path) and re.fullmatch(r"[a-f0-9]{64}[-a-z0-9]*\.[a-z0-9]+", path.name)]

    def settings(self, change=None):
        with self.lock:
            if self.root is not None:
                check_owned_path(self.root)
            if change is not None:
                if self.root is None:
                    raise MediaUnavailable("media-storage-unavailable")
                self._validate_settings(change)
                mode, size = change.get("mode", self.mode), change.get("cacheMaxBytes", self.cache_max)
                self._write(self.root / "settings.json", json.dumps({"mode": mode, "cacheMaxBytes": size}).encode())
                self.mode, self.cache_max = mode, size
                self._evict()
            return {"account": str(self.db.account), "mode": self.mode, "cacheMaxBytes": self.cache_max,
                    "cacheBytes": sum(p.stat().st_size for p in self._files("cache")),
                    "archiveBytes": sum(p.stat().st_size for p in self._files("archive"))}

    @staticmethod
    def _write(path, data):
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".write-", delete=False) as file:
            temporary = Path(file.name)
            file.write(data)
        try:
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)

    def _evict(self):
        files = sorted(self._files("cache"), key=lambda path: path.stat().st_mtime)
        total = sum(path.stat().st_size for path in files)
        for path in files:
            if total <= self.cache_max:
                break
            size = path.stat().st_size
            try:
                path.unlink()
                total -= size
            except OSError:
                continue

    def clear_cache(self):
        with self.lock:
            self._sticker_failures.clear()
            for path in self._files("cache"):
                try:
                    path.unlink()
                except OSError:
                    continue
            return self.settings()

    def _cache(self, key, extension, data, mime):
        if self.root is None or len(data) > self.cache_max:
            return MediaAsset(mime, data=data)
        with self.lock:
            target = self._folder("cache") / (key + "." + extension)
            self._write(target, data)
            self._evict()
        return MediaAsset(mime, data=data)

    def _archived(self, stable_id, suffix, mime):
        if self.root is not None:
            target = self._folder("archive") / (stable_id + "." + suffix)
            if target.is_file() and not _reparse(target):
                size = target.stat().st_size
                if size <= 0 or suffix in ("image", "sticker") and size > MAX_IMAGE or suffix == "silk" and size > MAX_VOICE:
                    raise MediaUnavailable("archive-invalid")
                with target.open("rb") as stream:
                    header = stream.read(32)
                if suffix == "mp4" and header[4:8] != b"ftyp" or suffix == "silk" and b"#!SILK_V3" not in header[:12]:
                    raise MediaUnavailable("archive-invalid")
                return MediaAsset(mime, path=target)
        return None

    def _retain(self, stable_id, suffix, asset):
        target = self._folder("archive") / (stable_id + "." + suffix)
        if _reparse(target) or target.exists() and not target.is_file():
            raise MediaUnavailable("media-storage-unavailable")
        if target.exists():
            return
        with self.lock:
            if asset.data is not None:
                self._write(target, asset.data)
            else:
                with tempfile.NamedTemporaryFile(dir=target.parent, prefix=".write-", delete=False) as file:
                    temporary = Path(file.name)
                    with asset.path.open("rb") as source:
                        shutil.copyfileobj(source, file, 1024 * 1024)
                try:
                    os.replace(temporary, target)
                finally:
                    temporary.unlink(missing_ok=True)

    def _image(self, user, row, thumbnail=False):
        md5 = self.downloader._img_md5(row)
        identifiers = [md5] if isinstance(md5, str) and re.fullmatch(r"[a-f0-9]{32}", md5) else []
        # Decoded content comes from the same precisely scoped source row. It may
        # contain the only usable MD5 when message_content is empty and XML is zstd.
        # Its content hash is a fallback: packed_info may name a different local file.
        content = row.get("decoded_content")
        if isinstance(content, str) and len(content) <= 128000 and "<!DOCTYPE" not in content.upper():
            try:
                root = ElementTree.fromstring(content[content.index("<"):].strip())
                node = root if root.tag == "img" else root.find(".//img")
                explicit = node.get("md5", "").lower() if node is not None else ""
                if re.fullmatch(r"[a-f0-9]{32}", explicit) and explicit not in identifiers:
                    identifiers.append(explicit)
            except (ValueError, ElementTree.ParseError):
                pass
        if not identifiers:
            raise MediaUnavailable("metadata-unavailable")
        account_root = Path(self.db.account_dir).resolve()
        base = account_root / "msg" / "attach" / hashlib.md5(user.encode()).hexdigest()
        if not base.resolve().is_relative_to(account_root):
            raise MediaUnavailable("local-file-unavailable")
        path = None
        for identifier in identifiers:
            candidate = (self.downloader._find_dat(user, identifier, row["create_time"], thumbnail=True) if thumbnail else None)
            candidate = candidate or self.downloader._find_dat(user, identifier, row["create_time"])
            candidate = candidate or self.downloader._find_dat(user, identifier, row["create_time"], thumbnail=True)
            if candidate and Path(candidate).name in (identifier + ".dat", identifier + "_t.dat") and Path(candidate).resolve().is_relative_to(base):
                path = Path(candidate)
                break
        if path is None:
            raise MediaUnavailable("local-file-unavailable")
        if path.stat().st_size > MAX_IMAGE:
            raise MediaUnavailable("image-too-large")
        with path.open("rb") as file:
            magic = file.read(6)
        aes_key = xor_key = None
        if magic == b"\x07\x08\x56\x32\x08\x07":
            derived = self.downloader._derive_cfg_key()
            if derived:
                aes_key, xor_key = derived
            else:
                aes_key = self.downloader._load_persisted_key()
                if not aes_key:
                    from media_keys import ImageKeyResolver
                    with self.lock:
                        if not hasattr(self, "_image_keys"):
                            self._image_keys = ImageKeyResolver(self.db)
                    initialized = self._image_keys.resolve(path)
                    if not initialized:
                        raise MediaUnavailable("local-key-unavailable")
                    aes_key, xor_key = initialized
                else:
                    xor_key = self.downloader._derive_xor_key(str(path))
        data = self.downloader.decrypt_image(path, aes_key=aes_key, xor_key=xor_key)
        if not isinstance(data, bytes) or len(data) > MAX_IMAGE:
            raise MediaUnavailable("image-too-large")
        if data.startswith(b"wxgf"):
            data = self._convert_wxgf(data)
        return MediaAsset(image_mime(data), data=data)

    @staticmethod
    def _sticker_image(data, identifier, aes_key=""):
        """Validate actual image bytes, keeping transparency and all animation frames."""
        from PIL import Image
        if not data or len(data) > MAX_IMAGE:
            raise MediaUnavailable("image-too-large")
        try:
            mime = image_mime(data)
        except MediaUnavailable:
            if not re.fullmatch(r"[a-fA-F0-9]{32}", aes_key) or len(data) % 16:
                raise MediaUnavailable("unsupported-format") from None
            from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
            from cryptography.hazmat.primitives.padding import PKCS7
            try:
                decryptor = Cipher(algorithms.AES(bytes.fromhex(aes_key)), modes.ECB()).decryptor()
                unpadder = PKCS7(128).unpadder()
                raw = decryptor.update(data) + decryptor.finalize()
                data = unpadder.update(raw) + unpadder.finalize()
                mime = image_mime(data)
            except ValueError:
                raise MediaUnavailable("image-decode-failed") from None
        if hashlib.md5(data).hexdigest() != identifier:
            raise MediaUnavailable("image-hash-mismatch")
        try:
            with Image.open(io.BytesIO(data)) as image:
                if image.width * image.height > 16_000_000:
                    raise MediaUnavailable("image-too-large")
                image.verify()
        except (OSError, ValueError, Image.DecompressionBombError):
            raise MediaUnavailable("image-decode-failed") from None
        return MediaAsset(mime, data=data)

    def _emoticon_key(self, path):
        from media_keys import EmoticonKeyResolver
        with self.lock:
            if not hasattr(self, "_emoticon_keys"):
                self._emoticon_keys = EmoticonKeyResolver(self.db)
        key = self._emoticon_keys.resolve(path)
        if not isinstance(key, bytes) or len(key) != 16:
            raise MediaUnavailable("local-key-unavailable")
        return key

    def _local_sticker(self, path, data, identifier, aes_key):
        try:
            return self._sticker_image(data, identifier, aes_key)
        except MediaUnavailable:
            pass
        # Local WeChat caches use account-derived CBC; CDN XML keys use ECB.
        if not data or len(data) % 16:
            raise MediaUnavailable("image-decode-failed")
        from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
        from cryptography.hazmat.primitives.padding import PKCS7
        key = self._emoticon_key(path)
        try:
            decryptor = Cipher(algorithms.AES(key), modes.CBC(key)).decryptor()
            raw = decryptor.update(data) + decryptor.finalize()
            unpadder = PKCS7(128).unpadder()
            plain = unpadder.update(raw) + unpadder.finalize()
        except ValueError:
            raise MediaUnavailable("image-decode-failed") from None
        return self._sticker_image(plain, identifier)

    def _store_sticker(self, account, identifier, product_id):
        """Read one indexed image from an account-local encrypted sticker pack."""
        if not product_id or len(product_id) > 512:
            raise MediaUnavailable("metadata-unavailable")
        from media_database import prepare_emoticon_databases
        if hasattr(self.db, "_keys"):
            prepare_emoticon_databases(self.db)
        matches = []
        for rel, raw_path, _size in getattr(self.db, "_db_files", ()):
            if str(rel).replace("\\", "/") != "emoticon/emoticon.db":
                continue
            path = Path(raw_path)
            check_owned_path(path)
            if not path.resolve().is_relative_to(account / "db_storage"):
                raise MediaUnavailable("emoticon-database-unavailable")
            if hasattr(self.db, "_keys") and rel not in self.db._keys:
                continue
            try:
                connection = self.db._open(rel)
            except RuntimeError:
                raise MediaUnavailable("emoticon-database-unavailable") from None
            try:
                matches.extend(connection.execute(
                    "SELECT emoticon_offset_,emoticon_size_ FROM kStoreEmoticonFilesTable "
                    "WHERE package_id_=? AND md5_ IN (?,?) LIMIT 2",
                    (product_id, identifier, identifier.upper())).fetchall())
            finally:
                connection.close()
        if len(matches) != 1:
            raise MediaUnavailable("sticker-unavailable")
        offset, size = matches[0]
        if type(offset) is not int or type(size) is not int or offset < 0 or not 0 < size <= MAX_IMAGE:
            raise MediaUnavailable("metadata-unavailable")
        package_id = hashlib.md5(product_id.encode("utf-8")).hexdigest()
        path = account / "business" / "emoticon" / "PersistStore" / package_id[:2] / package_id
        check_owned_path(path)
        if not path.resolve().is_relative_to(account):
            raise MediaUnavailable("sticker-unavailable")
        key = self._emoticon_key(path)
        start = offset // 16 * 16
        end = (offset + size + 15) // 16 * 16
        with path.open("rb") as stream:
            before = os.fstat(stream.fileno())
            if before.st_size % 16 or end > before.st_size:
                raise MediaUnavailable("image-decode-failed")
            # CBC needs only the prior ciphertext block, never the whole pack.
            stream.seek(start - 16 if start else 0)
            iv = stream.read(16) if start else key
            encrypted = stream.read(end - start)
            after = os.fstat(stream.fileno())
        if (len(iv) != 16 or len(encrypted) != end - start or
                (before.st_size, before.st_mtime_ns, before.st_ctime_ns) !=
                (after.st_size, after.st_mtime_ns, after.st_ctime_ns)):
            raise MediaUnavailable("image-decode-failed")
        from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
        decryptor = Cipher(algorithms.AES(key), modes.CBC(iv)).decryptor()
        raw = decryptor.update(encrypted) + decryptor.finalize()
        return self._sticker_image(raw[offset - start:offset - start + size], identifier)

    def _sticker_library(self, identifier):
        """The stills saved for one sticker (by content MD5) as ``(frames, duration_ms)``, or None."""
        if self.root is None or not (self.root / "stickers").is_dir():
            return None
        try:
            folder = self._folder("stickers")
            index = folder / (identifier + ".json")
            check_owned_path(index)
            if not index.is_file() or index.stat().st_size > 4096:
                return None
            value = json.loads(index.read_text(encoding="utf-8"))
            times, duration = value.get("frames"), value.get("durationMs")
            if (value.get("version") != 1 or not isinstance(times, list) or not 1 <= len(times) <= STICKER_FRAMES or
                    type(duration) is not int or not 0 <= duration <= 86_400_000):
                return None
            frames = []
            for position, time_ms in enumerate(times):
                path = folder / f"{identifier}-{position}.jpg"
                check_owned_path(path)
                if (type(time_ms) is not int or not 0 <= time_ms <= duration or not path.is_file() or
                        not 0 < path.stat().st_size <= MAX_FRAME_BYTES):
                    return None
                data = path.read_bytes()
                if not data.startswith(b"\xff\xd8\xff"):
                    return None
                frames.append((data, time_ms))
            return frames, duration
        except (OSError, ValueError, MediaUnavailable):
            return None

    def _sticker_frames(self, user, stable_id, row):
        """Stills of one sticker from the frame library, extracted and saved there on first use.

        The library is keyed by content MD5, so a sticker sent many times or by many friends is decoded once,
        and it outlives the cache limit and expiring CDN links. Account clearing removes it.
        """
        identity = sticker_identity(row.get("decoded_content"))
        if identity is None:
            raise MediaUnavailable("metadata-unavailable")
        saved = self._sticker_library(identity["id"])
        if saved:
            return saved
        try:
            frames, duration = analysis_frames(self.resolve(user, stable_id, row, "original").read())
        except MediaUnavailable as original_error:
            # Keep original animation when available. A verified local WXGF alias
            # is an analysis-only fallback, never an original or unverified cache.
            from sticker_wxgf import local_still
            try:
                still = local_still(self.db, identity["id"], self._emoticon_key, self._ffmpeg)
                return [(still, 0)], 0
            except (OSError, ValueError, RuntimeError, sqlite3.Error):
                raise original_error from None
        if self.root is not None and frames:
            try:
                with self.lock:
                    folder = self._folder("stickers")
                    for position, (data, _time_ms) in enumerate(frames):
                        self._write(folder / f"{identity['id']}-{position}.jpg", data)
                    # The index is written last: a reader never sees a partial set.
                    self._write(folder / (identity["id"] + ".json"), json.dumps(
                        {"version": 1, "durationMs": duration, "frames": [time_ms for _data, time_ms in frames]}).encode())
            except (OSError, MediaUnavailable):
                pass
        return frames, duration

    def sticker_texts(self, identities):
        """Official captions (by sticker MD5) and pack names (by pack id) of installed store stickers.

        Read from the account's emoticon index; a missing index or table only means no text.
        """
        wanted = sorted({item["id"] for item in identities})
        packs = sorted({item["pack"] for item in identities if item.get("pack")})
        captions, names = {}, {}
        if not wanted:
            return captions, names
        try:
            from media_database import prepare_emoticon_databases
            if hasattr(self.db, "_keys"):
                prepare_emoticon_databases(self.db)
            account = Path(self.db.account_dir).absolute()
            check_owned_path(account)
            account = account.resolve()
            for rel, raw_path, _size in getattr(self.db, "_db_files", ()):
                if str(rel).replace("\\", "/") != "emoticon/emoticon.db":
                    continue
                path = Path(raw_path)
                check_owned_path(path)
                if not path.resolve().is_relative_to(account / "db_storage"):
                    continue
                if hasattr(self.db, "_keys") and rel not in self.db._keys:
                    continue
                connection = self.db._open(rel)
                try:
                    found = {}
                    for start in range(0, len(wanted), 400):
                        batch = wanted[start:start + 400]
                        try:
                            rows = connection.execute(
                                "SELECT lower(md5_),lower(language_),caption_ FROM kStoreEmoticonCaptionsTable "
                                f"WHERE lower(md5_) IN ({','.join('?' for _ in batch)})", batch).fetchall()
                        except sqlite3.OperationalError:
                            break
                        for identifier, language, text in rows:
                            if isinstance(text, str) and text.strip():
                                found.setdefault(identifier, {}).setdefault(language or "", text.strip())
                    for identifier, values in found.items():
                        caption = _caption(values)
                        if caption:
                            captions.setdefault(identifier, caption)
                    for start in range(0, len(packs), 400):
                        batch = packs[start:start + 400]
                        try:
                            rows = connection.execute(
                                "SELECT package_id_,package_name_ FROM kStoreEmoticonPackageTable "
                                f"WHERE package_id_ IN ({','.join('?' for _ in batch)})", batch).fetchall()
                        except sqlite3.OperationalError:
                            break
                        for pack, name in rows:
                            name = " ".join(name.split())[:40] if isinstance(name, str) else ""
                            if name:
                                names.setdefault(pack, name)
                finally:
                    connection.close()
        except (OSError, ValueError, RuntimeError, sqlite3.Error, MediaUnavailable):
            pass
        return captions, names

    def _sticker(self, row):
        """Exact account-local lookup, then a bounded official-CDN fallback.

        URLs and AES keys remain inside the verified row; only image bytes are
        cached. This never uses XML-provided filenames or arbitrary remote hosts.
        """
        content = row.get("decoded_content")
        if not isinstance(content, str) or len(content) > 128000 or "<!DOCTYPE" in content.upper():
            raise MediaUnavailable("metadata-unavailable")
        try:
            root = ElementTree.fromstring(content[content.index("<"):].strip())
            node = root if root.tag == "emoji" else root.find(".//emoji")
            identifier = node.get("md5", "").lower() if node is not None else ""
        except (ValueError, ElementTree.ParseError):
            raise MediaUnavailable("metadata-unavailable") from None
        if not re.fullmatch(r"[a-f0-9]{32}", identifier):
            raise MediaUnavailable("metadata-unavailable")
        aes_key = node.get("aeskey", "")
        cache_key = hashlib.sha256(("sticker:" + identifier).encode()).hexdigest()

        def cached():
            if self.root is None:
                return None
            path = self._folder("cache") / (cache_key + ".sticker")
            check_owned_path(path)
            if path.is_file() and 0 < path.stat().st_size <= MAX_IMAGE:
                try:
                    with path.open("rb") as stream:
                        asset = self._sticker_image(stream.read(MAX_IMAGE + 1), identifier)
                    os.utime(path, None)
                    return asset
                except (OSError, MediaUnavailable):
                    pass
            return None

        stored = cached()
        if stored:
            return stored
        account = Path(self.db.account_dir).absolute()
        check_owned_path(account)
        account = account.resolve()

        def candidates():
            yield account / "business" / "emoticon" / "Persist" / identifier[:2] / identifier
            cache = account / "cache"
            check_owned_path(cache)
            if cache.is_dir():
                # Probe one exact file per month, without walking the media tree.
                for month in sorted(cache.iterdir(), reverse=True):
                    if re.fullmatch(r"\d{4}-\d{2}", month.name):
                        yield month / "Emoticon" / identifier[:2] / identifier

        for path in candidates():
            try:
                check_owned_path(path)
                if not path.resolve().is_relative_to(account) or not path.is_file():
                    continue
                if not 0 < path.stat().st_size <= MAX_IMAGE + 16:
                    continue
                with path.open("rb") as stream:
                    data = stream.read(MAX_IMAGE + 17)
                if not data or len(data) > MAX_IMAGE + 16:
                    continue
                return self._local_sticker(path, data, identifier, aes_key)
            except (OSError, ValueError, MediaUnavailable):
                continue
        try:
            return self._store_sticker(account, identifier, node.get("productid", ""))
        except (OSError, ValueError, sqlite3.Error, MediaUnavailable):
            pass
        from sticker_download import download_sticker, StickerDownloadError
        # Coalesce duplicate stickers without holding the chat source/config lock.
        with self._sticker_locks[int(identifier[0], 16)]:
            stored = cached()
            if stored:
                return stored
            urls = list(dict.fromkeys(node.get(key, "") for key in ("cdnurl", "encrypturl") if node.get(key)))
            failure_key = hashlib.sha256(json.dumps([identifier, urls, aes_key]).encode()).hexdigest()
            with self.lock:
                if self._sticker_failures.get(failure_key, 0) > time.monotonic():
                    raise MediaUnavailable("sticker-unavailable")
            for url in urls:
                try:
                    data = download_sticker(url, max_bytes=MAX_IMAGE)
                    asset = self._sticker_image(data, identifier, aes_key)
                    return self._cache(cache_key, "sticker", asset.read(), asset.mime)
                except (StickerDownloadError, MediaUnavailable):
                    continue
            with self.lock:
                if len(self._sticker_failures) >= 256:
                    self._sticker_failures.clear()
                self._sticker_failures[failure_key] = time.monotonic() + 60
        raise MediaUnavailable("sticker-unavailable")

    @staticmethod
    def _ffmpeg():
        try:
            import imageio_ffmpeg
            return imageio_ffmpeg.get_ffmpeg_exe()
        except (ImportError, RuntimeError):
            executable = shutil.which("ffmpeg")
            if executable:
                return executable
        raise MediaUnavailable("video-decoder-unavailable")

    def _run_ffmpeg(self, args):
        try:
            completed = subprocess.run([self._ffmpeg(), "-nostdin", "-v", "error", "-protocol_whitelist", "file,pipe", *args],
                capture_output=True, timeout=35, creationflags=0x08000000 if os.name == "nt" else 0)
        except (OSError, subprocess.TimeoutExpired):
            raise MediaUnavailable("media-conversion-failed") from None
        if completed.returncode or not completed.stdout or len(completed.stdout) > MAX_IMAGE:
            raise MediaUnavailable("media-conversion-failed")
        return completed.stdout

    def _convert_wxgf(self, data):
        offset = data.find(b"\x00\x00\x00\x01")
        if offset < 0:
            raise MediaUnavailable("unsupported-format")
        with tempfile.TemporaryDirectory(dir=self._folder("work")) as directory:
            source = Path(directory) / "input.hevc"
            source.write_bytes(data[offset:])
            return self._run_ffmpeg(["-f", "hevc", "-i", str(source), "-frames:v", "1", "-vf",
                "scale=1600:1600:force_original_aspect_ratio=decrease", "-f", "image2pipe", "-vcodec", "mjpeg", "pipe:1"])

    def _voice(self, user, row):
        if not row.get("server_id"):
            raise MediaUnavailable("metadata-unavailable")
        if hasattr(self.db, "_keys"):
            from media_database import prepare_voice_databases
            prepare_voice_databases(self.db)
        missing_key = False
        for rel, path, _ in self.db._db_files:
            if not Path(path).name.startswith("media_"):
                continue
            if hasattr(self.db, "_keys") and rel not in self.db._keys:
                missing_key = True
                continue
            conn = self.db._open(rel)
            try:
                cid = conn.execute("SELECT rowid FROM Name2Id WHERE user_name=?", (user,)).fetchone()
                if cid is None:
                    continue
                value = conn.execute("SELECT voice_data FROM VoiceInfo WHERE chat_name_id=? AND svr_id=? "
                    "ORDER BY create_time DESC LIMIT 1", (cid[0], row["server_id"])).fetchone()
            finally:
                conn.close()
            if value and isinstance(value[0], bytes):
                if len(value[0]) > MAX_VOICE:
                    raise MediaUnavailable("voice-too-large")
                return MediaAsset("audio/silk", data=value[0])
        raise MediaUnavailable("voice-database-key-unavailable" if missing_key else "local-file-unavailable")

    def _voice_playback(self, stable_id, asset):
        raw = asset.read()
        key = stable_id + "-" + hashlib.sha256(raw).hexdigest()
        target = self._folder("cache") / (key + ".wav")
        if target.is_file() and not _reparse(target):
            os.utime(target, None)
            return MediaAsset("audio/wav", path=target)
        try:
            import pysilk
        except ImportError:
            raise MediaUnavailable("voice-decoder-unavailable") from None
        class BoundedPCM(io.BytesIO):
            def write(self, value):
                if self.tell() + len(value) > 32 * 1024 * 1024:
                    raise ValueError("decoded voice too large")
                return super().write(value)
        pcm = BoundedPCM()
        try:
            pysilk.decode(io.BytesIO(raw), pcm, 24000)
        except Exception:
            raise MediaUnavailable("voice-decode-failed") from None
        if not pcm.tell():
            raise MediaUnavailable("voice-decode-failed")
        output = io.BytesIO()
        with wave.open(output, "wb") as wav:
            wav.setparams((1, 2, 24000, 0, "NONE", "not compressed"))
            wav.writeframes(pcm.getvalue())
        return self._cache(key, "wav", output.getvalue(), "audio/wav")

    def _video(self, row, *, user=None):
        packed = row.get("packed_info")
        ids = set(m.decode().lower() for m in re.findall(rb"[0-9a-fA-F]{32}", packed)) if isinstance(packed, bytes) else set()
        expected_hash, expected_size, filename = None, None, None
        content = row.get("decoded_content", row.get("content"))
        if "decoded_content" not in row and isinstance(content, bytes):
            content = self.db._friendly_content(content, "视频")
        if "decoded_content" not in row and (not content or content == "[视频]") and isinstance(row.get("compress_content"), bytes):
            content = self.db._friendly_content(row["compress_content"], "视频")
        if isinstance(content, str) and len(content) <= 128000 and "<!DOCTYPE" not in content.upper():
            try:
                root = ElementTree.fromstring(content[content.index("<"):].strip())
                node = root if root.tag == "videomsg" else root.find(".//videomsg")
                if node is not None:
                    value = node.get("md5", "").lower()
                    expected_hash = value if re.fullmatch(r"[a-f0-9]{32}", value) else None
                    value = node.get("length", "")
                    expected_size = int(value) if value.isdigit() and int(value) > 0 else None
                    value = node.get("filename", "")
                    filename = value if re.fullmatch(r"[\w .-]{1,160}\.mp4", value, re.I) else None
            except (ValueError, ElementTree.ParseError):
                pass
        if expected_hash:
            ids.add(expected_hash)
        if not ids and not (filename and expected_hash):
            raise MediaUnavailable("metadata-unavailable")
        account_root = Path(self.db.account_dir).resolve()
        identity = (str(account_root), user, tuple(sorted(ids)), expected_hash, expected_size, filename)
        with self.lock:
            cached = self._video_paths.get(identity)
        if cached is not None:
            path, signature, checked_at = cached
            try:
                check_owned_path(path)
                stamp = path.stat()
                current = (stamp.st_size, stamp.st_mtime_ns, stamp.st_ctime_ns)
                if time.monotonic() - checked_at < 30 and current == signature and path.is_file():
                    # File timestamps can collide on fast same-size replacements.
                    # Cache only the directory lookup, never the content proof.
                    with path.open("rb") as stream:
                        valid = stream.read(12)[4:8] == b"ftyp"
                        if valid and expected_hash:
                            stream.seek(0)
                            valid = hashlib.file_digest(stream, "md5").hexdigest() == expected_hash
                    after = path.stat()
                    if valid and (after.st_size, after.st_mtime_ns, after.st_ctime_ns) == signature:
                        return MediaAsset("video/mp4", path=path)
            except (OSError, MediaUnavailable):
                pass
            with self.lock:
                self._video_paths.pop(identity, None)
        # WeChat 4.x stores received videos alongside that conversation's images,
        # often using a cache filename unrelated to the message's content hash.
        # Search only the selected contact's attach directory, plus the legacy
        # shared video directory; content MD5 verifies renamed candidates.
        roots = [account_root / "msg" / "video"]
        if isinstance(user, str) and user:
            roots.insert(0, account_root / "msg" / "attach" / hashlib.md5(user.encode("utf-8")).hexdigest())
        names = {value + ".mp4" for value in ids}
        if filename:
            names.add(filename.lower())
        exact, others, inspected = [], [], 0
        for base in roots:
            if not base.resolve().is_relative_to(account_root):
                raise MediaUnavailable("local-file-unavailable")
            check_owned_path(base)
            for parent, dirs, files in os.walk(base, followlinks=False):
                dirs[:] = [name for name in dirs if not _reparse(Path(parent) / name)]
                dirs.sort(key=lambda name: name.casefold() != "video")
                for name in files:
                    if not name.lower().endswith(".mp4"):
                        continue
                    inspected += 1
                    path = Path(parent) / name
                    if _reparse(path) or not path.resolve().is_relative_to(base):
                        continue
                    if name.lower() in names:
                        exact.append(path)
                    elif expected_hash and expected_size and path.stat().st_size == expected_size:
                        others.append(path)
                if len(exact) + len(others) > 2000 or inspected > 20000:
                    break
            if len(exact) + len(others) > 2000 or inspected > 20000:
                break
        for path in exact + others:
            before = path.stat()
            file_signature = (before.st_size, before.st_mtime_ns, before.st_ctime_ns)
            if expected_size and before.st_size != expected_size:
                continue
            with path.open("rb") as stream:
                signature = stream.read(12)
                if len(signature) < 8 or signature[4:8] != b"ftyp":
                    continue
                if expected_hash:
                    stream.seek(0)
                    digest = hashlib.file_digest(stream, "md5").hexdigest()
                    if digest != expected_hash:
                        continue
            stamp = path.stat()
            if (stamp.st_size, stamp.st_mtime_ns, stamp.st_ctime_ns) != file_signature:
                continue
            with self.lock:
                if len(self._video_paths) >= 128:
                    self._video_paths.clear()
                self._video_paths[identity] = (path, file_signature, time.monotonic())
            return MediaAsset("video/mp4", path=path)
        raise MediaUnavailable("local-file-unavailable")

    def _frame(self, stable_id, asset, time_ms=0):
        stamp = asset.path.stat()
        key = stable_id + "-" + hashlib.sha256(f"{stamp.st_size}:{stamp.st_mtime_ns}:{time_ms}".encode()).hexdigest()
        target = self._folder("cache") / (key + ".jpg")
        if target.is_file() and not _reparse(target):
            os.utime(target, None)
            return MediaAsset("image/jpeg", path=target)
        data = self._run_ffmpeg(["-ss", str(time_ms / 1000), "-i", str(asset.path), "-frames:v", "1", "-vf",
            "scale=1024:1024:force_original_aspect_ratio=decrease", "-f", "image2pipe", "-vcodec", "mjpeg", "pipe:1"])
        image_mime(data)
        return self._cache(key, "jpg", data, "image/jpeg")

    def _original(self, user, stable_id, row, thumbnail=False):
        kind = media_kind(row["local_type"])
        suffix, mime = {"image": ("image", "application/octet-stream"), "sticker": ("sticker", "application/octet-stream"),
                        "voice": ("silk", "audio/silk"), "video": ("mp4", "video/mp4")}[kind]
        retained = self._archived(stable_id, suffix, mime)
        if retained:
            if kind in ("image", "sticker"):
                data = retained.read()
                return MediaAsset(image_mime(data), data=data)
            return retained
        if kind == "sticker":
            return self._sticker(row)
        return self._image(user, row, thumbnail) if kind == "image" else self._voice(user, row) if kind == "voice" else self._video(row, user=user)

    def archive(self, user, stable_id, row):
        original = self._original(user, stable_id, row)
        suffix = {"image": "image", "sticker": "sticker", "voice": "silk", "video": "mp4"}[media_kind(row["local_type"])]
        self._retain(stable_id, suffix, original)
        return {"archived": True, "id": stable_id, **self.settings()}

    def resolve(self, user, stable_id, row, variant="original", time_ms=0):
        if variant not in ("thumbnail", "original", "playback", "frame"):
            raise ValueError("invalid media variant")
        kind = media_kind(row["local_type"])
        if kind is None:
            raise MediaUnavailable("unsupported-media")
        original = self._original(user, stable_id, row, variant == "thumbnail" and self.mode == "reference")
        if self.mode == "archive":
            self._retain(stable_id, {"image": "image", "sticker": "sticker", "voice": "silk", "video": "mp4"}[kind], original)
        if kind == "sticker":
            return original
        if kind == "image":
            if variant == "thumbnail":
                try:
                    from PIL import Image
                    with Image.open(io.BytesIO(original.read())) as image:
                        image.thumbnail((480, 480))
                        output = io.BytesIO()
                        image.convert("RGB").save(output, "JPEG", quality=80)
                    return MediaAsset("image/jpeg", data=output.getvalue())
                except ImportError:
                    return original
                except Exception:
                    raise MediaUnavailable("image-decode-failed") from None
            return original
        if kind == "voice":
            return self._voice_playback(stable_id, original) if variant in ("original", "playback") else original
        return self._frame(stable_id, original, time_ms) if variant in ("thumbnail", "frame") else original

    def analysis(self, user, stable_id, row, metadata, cancel=None, frames=1):
        kind = media_kind(row["local_type"])
        result = {**metadata, "kind": kind, "items": []}
        if kind == "voice":
            if not result.get("transcript"):
                result["error"] = "wechat-transcript-unavailable"
            return result
        if kind == "sticker" and frames > 1:
            try:
                stills, duration = self._sticker_frames(user, stable_id, row)
            except MediaUnavailable as exc:
                result["error"] = str(exc)
                return result
            result["items"] = [{"bytes": data, "mime": "image/jpeg", "timeMs": time_ms}
                               for data, time_ms in stills[:frames]]
            if duration:
                result.update(sampling="animated-frames", durationMs=duration)
            return result
        duration = metadata.get("durationMs", 0)
        times = [0] if kind in ("image", "sticker") or duration < 3000 else [0, duration // 3, duration * 2 // 3]
        video = None
        for position in times:
            if cancel is not None and cancel.is_set():
                result["error"] = "cancelled"
                break
            try:
                if kind == "video":
                    if video is None:
                        video = self.resolve(user, stable_id, row, "original")
                    asset = self._frame(stable_id, video, position)
                else:
                    asset = self.resolve(user, stable_id, row, "original")
                normalized, animated = analysis_image(asset.read())
                result["items"].append({"bytes": normalized, "mime": "image/jpeg", **({"timeMs": position} if kind == "video" else {})})
                if animated:
                    result["sampling"] = "animated-image-first-frame"
            except MediaUnavailable as exc:
                result["error"] = str(exc)
                break
        return result
